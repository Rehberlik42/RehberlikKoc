-- =============================================================================
-- Bildirim tetikleyicileri (SECURITY DEFINER: RLS'i aşarak karşı tarafa yazar)
-- =============================================================================
CREATE OR REPLACE FUNCTION public.appointment_reminder_offsets()
RETURNS TABLE (offset_interval interval, label text)
LANGUAGE sql IMMUTABLE AS $$
  VALUES
    (interval '24 hours', '24 saat'),
    (interval '1 hour',  '1 saat'),
    (interval '10 minutes', '10 dakika');
$$;

CREATE OR REPLACE FUNCTION public.create_appointment_reminders(p_appointment public.appointments)
RETURNS void
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  r record;
  v_when text;
BEGIN
  -- Eski hatırlatmaları temizle (saat değişmiş olabilir)
  DELETE FROM public.notifications
  WHERE appointment_id = p_appointment.id AND type = 'reminder' AND deliver_at > now();

  v_when := to_char(p_appointment.appointment_date AT TIME ZONE 'Europe/Istanbul', 'DD.MM.YYYY HH24:MI');

  FOR r IN SELECT * FROM public.appointment_reminder_offsets() LOOP
    IF p_appointment.appointment_date - r.offset_interval > now() THEN
      INSERT INTO public.notifications (user_id, type, title, body, appointment_id, deliver_at)
      VALUES
        (p_appointment.student_id, 'reminder',
         'Randevu hatırlatma',
         'Randevunuza ' || r.label || ' kaldı · ' || v_when,
         p_appointment.id,
         p_appointment.appointment_date - r.offset_interval),
        (p_appointment.teacher_id, 'reminder',
         'Randevu hatırlatma',
         'Randevunuza ' || r.label || ' kaldı · ' || v_when,
         p_appointment.id,
         p_appointment.appointment_date - r.offset_interval);
    END IF;
  END LOOP;
END;
$$;

CREATE OR REPLACE FUNCTION public.handle_appointment_notifications()
RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  v_actor uuid := auth.uid();
  v_student_name text;
  v_when text;
  v_proposed text;
BEGIN
  SELECT full_name INTO v_student_name FROM public.profiles WHERE id = NEW.student_id;
  v_when := to_char(NEW.appointment_date AT TIME ZONE 'Europe/Istanbul', 'DD.MM.YYYY HH24:MI');

  IF TG_OP = 'INSERT' THEN
    IF v_actor = NEW.student_id THEN
      INSERT INTO public.notifications (user_id, type, title, body, appointment_id)
      VALUES (NEW.teacher_id, 'appointment_request', 'Yeni randevu talebi',
              coalesce(v_student_name, 'Öğrenci') || ' · ' || v_when, NEW.id);
    ELSIF NEW.status = 'confirmed' THEN
      INSERT INTO public.notifications (user_id, type, title, body, appointment_id)
      VALUES (NEW.student_id, 'appointment_confirmed', 'Yeni randevu oluşturuldu',
              'Öğretmeniniz sizin için bir randevu oluşturdu · ' || v_when, NEW.id);
      PERFORM public.create_appointment_reminders(NEW);
    END IF;
    RETURN NEW;
  END IF;

  -- UPDATE
  IF NEW.status IS DISTINCT FROM OLD.status THEN
    IF NEW.status = 'confirmed' THEN
      IF v_actor = NEW.student_id THEN
        INSERT INTO public.notifications (user_id, type, title, body, appointment_id)
        VALUES (NEW.teacher_id, 'proposal_accepted', 'Önerilen saat kabul edildi',
                coalesce(v_student_name, 'Öğrenci') || ' önerdiğiniz saati kabul etti · ' || v_when, NEW.id);
      ELSE
        INSERT INTO public.notifications (user_id, type, title, body, appointment_id)
        VALUES (NEW.student_id, 'appointment_confirmed', 'Randevunuz onaylandı',
                v_when || ' tarihli randevunuz onaylandı.', NEW.id);
      END IF;
      PERFORM public.create_appointment_reminders(NEW);
    ELSIF NEW.status = 'proposed' THEN
      v_proposed := to_char(NEW.proposed_date AT TIME ZONE 'Europe/Istanbul', 'DD.MM.YYYY HH24:MI');
      INSERT INTO public.notifications (user_id, type, title, body, appointment_id)
      VALUES (NEW.student_id, 'time_proposed', 'Öğretmeniniz farklı bir saat önerdi',
              'Önerilen yeni saat: ' || coalesce(v_proposed, '-'), NEW.id);
    ELSIF NEW.status = 'pending' AND OLD.status = 'proposed' THEN
      -- Öğrenci öneriyi kabul etmeyip farklı bir saat seçti
      INSERT INTO public.notifications (user_id, type, title, body, appointment_id)
      VALUES (NEW.teacher_id, 'appointment_request', 'Öğrenci farklı bir saat seçti',
              coalesce(v_student_name, 'Öğrenci') || ' · yeni talep: ' || v_when, NEW.id);
    ELSIF NEW.status = 'rejected' THEN
      INSERT INTO public.notifications (user_id, type, title, body, appointment_id)
      VALUES (NEW.student_id, 'appointment_rejected', 'Randevu talebiniz reddedildi',
              coalesce(NEW.rejection_reason, v_when || ' tarihli talebiniz reddedildi.'), NEW.id);
    ELSIF NEW.status = 'cancelled' THEN
      INSERT INTO public.notifications (user_id, type, title, body, appointment_id)
      VALUES (CASE WHEN v_actor = NEW.student_id THEN NEW.teacher_id ELSE NEW.student_id END,
              'appointment_cancelled', 'Randevu iptal edildi',
              v_when || ' tarihli randevu iptal edildi.', NEW.id);
      DELETE FROM public.notifications
      WHERE appointment_id = NEW.id AND type = 'reminder' AND deliver_at > now();
    ELSIF NEW.status IN ('completed', 'in_progress') THEN
      NULL; -- bildirim gerekmez
    END IF;
  ELSIF NEW.appointment_date IS DISTINCT FROM OLD.appointment_date AND NEW.status = 'confirmed' THEN
    INSERT INTO public.notifications (user_id, type, title, body, appointment_id)
    VALUES (CASE WHEN v_actor = NEW.student_id THEN NEW.teacher_id ELSE NEW.student_id END,
            'appointment_updated', 'Randevu saati güncellendi',
            'Yeni randevu saati: ' || v_when, NEW.id);
    PERFORM public.create_appointment_reminders(NEW);
  END IF;

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_appointment_notifications ON public.appointments;
CREATE TRIGGER trg_appointment_notifications
  AFTER INSERT OR UPDATE ON public.appointments
  FOR EACH ROW EXECUTE FUNCTION public.handle_appointment_notifications();

-- =============================================================================
-- RPC: öğretmenin dolu saat aralıkları (öğrenciye kişisel veri sızdırmadan)
-- =============================================================================
CREATE OR REPLACE FUNCTION public.get_teacher_busy_slots(
  p_teacher_id uuid, p_from date, p_to date
)
RETURNS TABLE (starts_at timestamptz, ends_at timestamptz)
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT a.appointment_date,
         a.appointment_date + make_interval(mins => a.duration_minutes)
  FROM public.appointments a
  WHERE a.teacher_id = p_teacher_id
    AND a.status IN ('pending','proposed','confirmed','in_progress')
    AND (a.appointment_date AT TIME ZONE 'Europe/Istanbul')::date BETWEEN p_from AND p_to
    AND (
      auth.uid() = p_teacher_id
      OR public.is_student_of_teacher(p_teacher_id)
    );
$$;

-- =============================================================================
-- Program görevi tamamlanınca bağlı görüşme kararını da tamamlandı işaretle
-- =============================================================================
CREATE OR REPLACE FUNCTION public.sync_decision_completion()
RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  IF NEW.is_completed IS DISTINCT FROM OLD.is_completed THEN
    UPDATE public.meeting_decisions
    SET is_completed = NEW.is_completed,
        completed_at = CASE WHEN NEW.is_completed THEN now() ELSE NULL END
    WHERE study_plan_task_id = NEW.id;
  END IF;
  RETURN NEW;
END;
$$;
REVOKE EXECUTE ON FUNCTION public.sync_decision_completion() FROM PUBLIC, anon, authenticated;
DROP TRIGGER IF EXISTS trg_sync_decision_completion ON public.study_plan_tasks;
CREATE TRIGGER trg_sync_decision_completion
  AFTER UPDATE ON public.study_plan_tasks
  FOR EACH ROW EXECUTE FUNCTION public.sync_decision_completion();

