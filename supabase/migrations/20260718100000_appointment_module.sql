-- Yardımcı: oturum açan kullanıcı verilen öğretmenin öğrencisi mi?
CREATE OR REPLACE FUNCTION public.is_student_of_teacher(p_teacher_id uuid)
RETURNS boolean
LANGUAGE sql STABLE SECURITY INVOKER SET search_path = public AS $$
  SELECT EXISTS (
    SELECT 1 FROM public.profiles p
    WHERE p.id = auth.uid() AND p.teacher_id = p_teacher_id AND p.role = 'student'
  );
$$;

