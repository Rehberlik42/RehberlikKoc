-- =============================================================================
-- MINDORA: Randevu Yönetim Modülü
-- Öğretmen müsaitliği, randevu yaşam döngüsü (talep → onay/öneri → görüşme →
-- not), yapılandırılmış görüşme notları, karar/görev takibi ve uygulama içi
-- bildirim + hatırlatma sistemi.
-- =============================================================================

-- ─── 1. Öğretmen randevu ayarları ────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.teacher_appointment_settings (
  teacher_id uuid PRIMARY KEY REFERENCES public.profiles(id) ON DELETE CASCADE,
  slot_minutes int NOT NULL DEFAULT 30 CHECK (slot_minutes BETWEEN 10 AND 180),
  buffer_minutes int NOT NULL DEFAULT 10 CHECK (buffer_minutes BETWEEN 0 AND 60),
  max_daily int NOT NULL DEFAULT 8 CHECK (max_daily BETWEEN 1 AND 30),
  updated_at timestamptz NOT NULL DEFAULT now()
);

-- ─── 2. Haftalık müsaitlik kuralları (gün başına birden çok aralık) ──────────
-- day_of_week: ISO — 1 = Pazartesi … 7 = Pazar
CREATE TABLE IF NOT EXISTS public.teacher_availability_rules (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  teacher_id uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  day_of_week int NOT NULL CHECK (day_of_week BETWEEN 1 AND 7),
  start_time time NOT NULL,
  end_time time NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  CHECK (start_time < end_time)
);

CREATE INDEX IF NOT EXISTS idx_availability_rules_teacher
  ON public.teacher_availability_rules (teacher_id, day_of_week);

-- ─── 3. İstisnalar: tatil / izin / tek seferlik kapalı saat ──────────────────
-- start_time & end_time NULL ise tüm gün kapalıdır.
CREATE TABLE IF NOT EXISTS public.teacher_availability_exceptions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  teacher_id uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  date date NOT NULL,
  start_time time,
  end_time time,
  reason text,
  created_at timestamptz NOT NULL DEFAULT now(),
  CHECK (
    (start_time IS NULL AND end_time IS NULL)
    OR (start_time IS NOT NULL AND end_time IS NOT NULL AND start_time < end_time)
  )
);

CREATE INDEX IF NOT EXISTS idx_availability_exceptions_teacher
  ON public.teacher_availability_exceptions (teacher_id, date);

-- ─── 4. appointments tablosunu genişlet ──────────────────────────────────────
ALTER TABLE public.appointments
  ADD COLUMN IF NOT EXISTS meeting_type text NOT NULL DEFAULT 'student',
  ADD COLUMN IF NOT EXISTS meeting_format text NOT NULL DEFAULT 'online',
  ADD COLUMN IF NOT EXISTS created_by uuid REFERENCES public.profiles(id) ON DELETE SET NULL,
  ADD COLUMN IF NOT EXISTS proposed_date timestamptz,
  ADD COLUMN IF NOT EXISTS proposed_by uuid,
  ADD COLUMN IF NOT EXISTS rejection_reason text,
  ADD COLUMN IF NOT EXISTS started_at timestamptz,
  ADD COLUMN IF NOT EXISTS completed_at timestamptz;

ALTER TABLE public.appointments DROP CONSTRAINT IF EXISTS appointments_status_check;
ALTER TABLE public.appointments ADD CONSTRAINT appointments_status_check
  CHECK (status IN ('pending','proposed','confirmed','in_progress','completed','cancelled','rejected'));

ALTER TABLE public.appointments DROP CONSTRAINT IF EXISTS appointments_meeting_type_check;
ALTER TABLE public.appointments ADD CONSTRAINT appointments_meeting_type_check
  CHECK (meeting_type IN ('student','parent','joint','program_review','exam_analysis','preference','intro','other'));

ALTER TABLE public.appointments DROP CONSTRAINT IF EXISTS appointments_meeting_format_check;
ALTER TABLE public.appointments ADD CONSTRAINT appointments_meeting_format_check
  CHECK (meeting_format IN ('online','in_person','phone'));

CREATE INDEX IF NOT EXISTS idx_appointments_teacher_date
  ON public.appointments (teacher_id, appointment_date);

-- ─── 5. Görüşme notları (paylaşılabilir alanlar) ─────────────────────────────
CREATE TABLE IF NOT EXISTS public.meeting_notes (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  appointment_id bigint NOT NULL UNIQUE REFERENCES public.appointments(id) ON DELETE CASCADE,
  teacher_id uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  student_id uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  subject_topic text,
  student_opinion text,
  parent_opinion text,
  visibility text NOT NULL DEFAULT 'teacher'
    CHECK (visibility IN ('teacher','teacher_student','teacher_parent','all')),
  follow_up_topics jsonb NOT NULL DEFAULT '[]'::jsonb,
  next_meeting_date date,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_meeting_notes_student
  ON public.meeting_notes (student_id, created_at DESC);

-- ─── 6. Öğretmenin özel değerlendirmesi (asla öğrenci/veliye açılmaz) ────────
-- Ayrı tabloda tutulur; RLS yalnızca öğretmene izin verir. Böylece görünürlük
-- ayarı ne olursa olsun API üzerinden dahi sızamaz.
CREATE TABLE IF NOT EXISTS public.meeting_private_notes (
  appointment_id bigint PRIMARY KEY REFERENCES public.appointments(id) ON DELETE CASCADE,
  teacher_id uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  evaluation text,
  updated_at timestamptz NOT NULL DEFAULT now()
);

-- ─── 7. Kararlar / görevler / takip maddeleri ────────────────────────────────
CREATE TABLE IF NOT EXISTS public.meeting_decisions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  appointment_id bigint NOT NULL REFERENCES public.appointments(id) ON DELETE CASCADE,
  student_id uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  teacher_id uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  kind text NOT NULL DEFAULT 'decision' CHECK (kind IN ('decision','task','follow_up')),
  text_content text NOT NULL,
  is_completed boolean NOT NULL DEFAULT false,
  completed_at timestamptz,
  study_plan_task_id bigint REFERENCES public.study_plan_tasks(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_meeting_decisions_appointment
  ON public.meeting_decisions (appointment_id);
CREATE INDEX IF NOT EXISTS idx_meeting_decisions_student
  ON public.meeting_decisions (student_id, is_completed);

-- ─── 8. Uygulama içi bildirimler + zamanlanmış hatırlatmalar ─────────────────
-- deliver_at gelecekte olan satırlar hatırlatmadır; zamanı gelince zilde görünür.
CREATE TABLE IF NOT EXISTS public.notifications (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  type text NOT NULL,
  title text NOT NULL,
  body text,
  appointment_id bigint REFERENCES public.appointments(id) ON DELETE CASCADE,
  deliver_at timestamptz NOT NULL DEFAULT now(),
  is_read boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_notifications_user
  ON public.notifications (user_id, deliver_at DESC);

